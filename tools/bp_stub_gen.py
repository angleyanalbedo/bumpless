#!/usr/bin/env python3
"""
bp_stub_gen.py - Developer Migration & Transparent Wrapper Stub Generator

Responsibilities:
1. Implements Scheme 1 (透明内联桩 / Inline Wrapper Stubs):
   Parses function declarations and IDs from `common_ids.h`, then automatically generates
   type-safe native C inline wrappers (`include/bp_stubs.h`).
   Callers write normal C function calls: `fb_motor_call(ctx, inst_id, now_ns)`!
2. Scaffolding Tool (`scaffold`):
   Helps developers migrate legacy C functions into Bumpless hot-swappable modules
   with zero boilerplate.
"""

import os
import re
import sys
import argparse
from typing import List, Dict

def parse_common_ids(header_path: str) -> List[Dict[str, str]]:
    """
    Parses FN_* definitions from common_ids.h
    """
    if not os.path.exists(header_path):
        raise FileNotFoundError(f"Cannot find header file: {header_path}")

    with open(header_path, "r", encoding="utf-8") as f:
        content = f.read()

    # Match enum { ... } blocks or #define FN_*
    fn_list = []
    # Match lines like "FN_MAIN = 0," or "FN_FB_MOTOR = 1"
    pattern = re.compile(r"\b(FN_[A-Za-z0-9_]+)\s*(?:=\s*(\d+))?")
    for line in content.splitlines():
        line = line.strip()
        if line.startswith("//") or line.startswith("/*"):
            continue
        m = pattern.search(line)
        if m:
            fn_symbol = m.group(1)
            # Derive friendly function name:
            # FN_MAIN -> main_fn
            # FN_FB_MOTOR -> fb_motor
            raw_name = fn_symbol[3:].lower()
            fn_list.append({
                "symbol": fn_symbol,
                "name": raw_name,
                "call_name": f"{raw_name}_call",
                "direct_name": f"{raw_name}_call_direct"
            })
    return fn_list

def generate_stubs_header(fn_list: List[Dict[str, str]], out_path: str):
    """
    Generates include/bp_stubs.h
    """
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("/*\n")
        f.write(" * bp_stubs.h - Auto-generated Native C Transparent Call Wrappers (Scheme 1)\n")
        f.write(" * Generated by: tools/bp_stub_gen.py - DO NOT EDIT MANUALLY\n")
        f.write(" *\n")
        f.write(" * Eliminates BP_CALL(...) boilerplate from host and caller code!\n")
        f.write(" * Callers write standard, type-safe C function calls.\n")
        f.write(" */\n\n")
        f.write("#ifndef BP_STUBS_H\n")
        f.write("#define BP_STUBS_H\n\n")
        f.write('#include "bumpless.h"\n')
        f.write('#include "common_ids.h"\n\n')
        f.write("#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n")

        for fn in fn_list:
            sym = fn["symbol"]
            call_fn = fn["call_name"]
            direct_fn = fn["direct_name"]

            f.write(f"/* === Wrappers for {sym} === */\n")
            f.write(f"/**\n")
            f.write(f" * @brief Calls {sym} via decoupled instance slot ID (Recommended)\n")
            f.write(f" */\n")
            f.write(f"static inline void {call_fn}(BpRuntimeCtx* ctx, uint32_t inst_id, uint64_t now_ns) {{\n")
            f.write(f"    BP_CALL(ctx, {sym}, inst_id, now_ns);\n")
            f.write(f"}}\n\n")

            f.write(f"/**\n")
            f.write(f" * @brief Calls {sym} via direct instance pointer (Direct Pointer Mode)\n")
            f.write(f" */\n")
            f.write(f"static inline void {direct_fn}(BpRuntimeCtx* ctx, void* self, uint64_t now_ns) {{\n")
            f.write(f"    ctx->fn_table[{sym}](ctx, self, now_ns);\n")
            f.write(f"}}\n\n")

        f.write("#ifdef __cplusplus\n}\n#endif\n\n")
        f.write("#endif /* BP_STUBS_H */\n")
    print(f"[bp_stub_gen] Generated {len(fn_list)} wrapper stubs in '{out_path}'")

def scaffold_module(module_name: str, fn_symbol: str, struct_name: str, out_file: str):
    """
    Scaffolds a new hot-swappable module C file
    """
    os.makedirs(os.path.dirname(os.path.abspath(out_file)), exist_ok=True)
    c_code = f"""/*
 * {os.path.basename(out_file)} - Scaffolded by tools/bp_stub_gen.py
 */
#include "bumpless.h"
#include "common_ids.h"
#include "bp_module.h"
#include <stdio.h>

/* State struct: Raw POD with ZERO runtime metadata bloat */
typedef struct {{
    int32_t count;
    bool    enabled;
}} {struct_name};

static void {module_name}_init(void* self) {{
    {struct_name}* s = ({struct_name}*)self;
    s->count   = 0;
    s->enabled = true;
}}

static void {module_name}_exec(BpRuntimeCtx* ctx, void* self, uint64_t now_ns) {{
    (void)ctx;
    (void)now_ns;
    {struct_name}* s = ({struct_name}*)self;
    if (s->enabled) {{
        s->count++;
    }}
    printf("[{module_name}] count=%d\\n", s->count);
}}

/*
 * Zero-boilerplate module export macro:
 * Automatically binds struct size, init, exec, and exports bp_get_module_abi()
 */
BP_EXPORT_MODULE(
    {fn_symbol},
    "{module_name}",
    0x20000001ULL, /* Seed layout hash (or compile-time generated) */
    {struct_name},
    {module_name}_init,
    {module_name}_exec
);
"""
    with open(out_file, "w", encoding="utf-8") as f:
        f.write(c_code)
    print(f"[bp_stub_gen] Scaffolded module template: '{out_file}'")

def main():
    parser = argparse.ArgumentParser(description="Bumpless Transparent Stub Generator & Scaffolding Tool")
    subparsers = parser.add_subparsers(dest="command", required=True)

    # Subcommand: generate
    p_gen = subparsers.add_parser("generate", help="Generate inline call wrapper stubs from common_ids.h")
    p_gen.add_argument("--header", default="include/common_ids.h", help="Path to common_ids.h")
    p_gen.add_argument("--out", default="include/bp_stubs.h", help="Output path for bp_stubs.h")

    # Subcommand: scaffold
    p_scaf = subparsers.add_parser("scaffold", help="Scaffold a new hot-swappable module C template")
    p_scaf.add_argument("--name", required=True, help="Module function base name (e.g. fn_pid)")
    p_scaf.add_argument("--fn-id", required=True, help="Function symbol in common_ids.h (e.g. FN_FB_PID)")
    p_scaf.add_argument("--struct", required=True, help="State POD struct name (e.g. FbPid)")
    p_scaf.add_argument("--out", required=True, help="Output C file path")

    args = parser.parse_args()

    if args.command == "generate":
        fn_list = parse_common_ids(args.header)
        generate_stubs_header(fn_list, args.out)
    elif args.command == "scaffold":
        scaffold_module(args.name, args.fn_id, args.struct, args.out)

if __name__ == "__main__":
    main()
